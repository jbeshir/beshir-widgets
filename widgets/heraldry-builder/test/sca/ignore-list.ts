// test/fixtures/sca/ignored.json: every current armory record the widget can't yet express, with its
// gap tags, written by `npm run sca:ignore` (update-ignore-list.ts) and read by the armorial test.
// Keys and tags only — never blazon text, which stays in oanda.db alone.
//
// Records are grouped by their primary gap: of a record's gap categories, the one ranked highest by
// single-gap count (rankCategories). Groups follow that ranking, so the file reads as a to-do list:
// the first group is the gap whose fix alone unlocks the most records. Inside a group records are
// in regid order, one per line, so a regenerated list diffs readably.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { GAP_CATEGORIES, categoryOf } from './gaps';
import { rankCategories } from './ranking';

export const IGNORED_PATH = fileURLToPath(new URL('../fixtures/sca/ignored.json', import.meta.url));

export interface IgnoreGroup {
  /** The primary gap category of every record in the group. */
  category: string;
  description: string;
  /** Records whose only gap is this category: what closing it alone would unlock. */
  singleGap: number;
  /** Record key → its gap tags. */
  records: Record<string, string[]>;
}

export interface IgnoreList {
  $comment: string;
  groups: IgnoreGroup[];
}

const COMMENT = 'Generated by `npm run sca:ignore`; see README.md. Record keys and gap tags only.';

/** regid order; any `line:` key (a record without a regid) after them. */
const keyOrder = (a: string, b: string): number => {
  const [na, nb] = [a, b].map((k) => (k.startsWith('regid:') ? Number(k.slice(6)) : Infinity));
  return na !== nb ? na - nb : a < b ? -1 : a > b ? 1 : 0;
};

export function buildIgnoreList(entries: readonly { key: string; tags: readonly string[] }[]): IgnoreList {
  const ranking = rankCategories(entries.map((e) => e.tags));
  const groups = ranking.map((r): IgnoreGroup => ({
    category: r.id,
    description: GAP_CATEGORIES.find((c) => c.id === r.id)?.description ?? '',
    singleGap: r.singleGap,
    records: {},
  }));
  const rank = new Map(ranking.map((r, i) => [r.id, i]));
  for (const { key, tags } of [...entries].sort((a, b) => keyOrder(a.key, b.key))) {
    const primary = Math.min(...tags.map((t) => rank.get(categoryOf(t))!));
    groups[primary].records[key] = [...tags];
  }
  return { $comment: COMMENT, groups: groups.filter((g) => Object.keys(g.records).length) };
}

/** JSON with each group's header on one line and one record per line. */
export function serialiseIgnoreList(list: IgnoreList): string {
  const j = JSON.stringify;
  const group = (g: IgnoreGroup) => [
    `    {"category": ${j(g.category)}, "description": ${j(g.description)}, "singleGap": ${g.singleGap}, "records": {`,
    Object.entries(g.records).map(([key, tags]) => `      ${j(key)}: [${tags.map((t) => j(t)).join(', ')}]`).join(',\n'),
    '    }}',
  ].join('\n');
  return `{\n  "$comment": ${j(list.$comment)},\n  "groups": [\n${list.groups.map(group).join(',\n')}\n  ]\n}\n`;
}

export function readIgnoreList(): IgnoreList {
  return JSON.parse(readFileSync(IGNORED_PATH, 'utf8')) as IgnoreList;
}
